def _spec(
    chart_id: str,
    title: str,
    research_question: str,
    reason_for_inclusion: str,
    analysis_level: str,
    applicable_data_type: str,
    chart_type: str,
    x_axis: str,
    y_axis: str,
    unit: str,
    grouping: str,
    statistical_method: str,
    calculation_or_formula: str,
    module_owner: str,
    notebook_section: str,
    tests: Sequence[str],
    acceptance_criteria: str,
    preprocessing: Sequence[str] = (),
    sampling: str = SAMPLING_DEFAULT,
    limitations: Sequence[str] = LIMITATIONS_DEFAULT,
    status: ChartStatus = ChartStatus.IMPLEMENTED,
    reason: str = "",
) -> ChartSpec:
    return ChartSpec(
        chart_id=chart_id,
        title=title,
        research_question=research_question,
        reason_for_inclusion=reason_for_inclusion,
        analysis_level=analysis_level,
        applicable_data_type=applicable_data_type,
        input_source_ids=(),
        input_columns=(),
        preprocessing_prerequisites=tuple(preprocessing),
        statistical_method=statistical_method,
        calculation_or_formula=calculation_or_formula,
        chart_type=chart_type,
        x_axis=x_axis,
        y_axis=y_axis,
        unit=unit,
        grouping=grouping,
        sampling_strategy=sampling,
        missing_handling=MISSING_DEFAULT,
        outlier_handling=OUTLIER_DEFAULT,
        expected_interpretation=(
            "Kết luận chỉ được ghi khi số liệu kiểm chứng tồn tại; nếu thiếu bằng "
            "chứng thì ghi 'Chưa đủ dữ liệu hoặc điều kiện kiểm chứng để đưa ra "
            "kết luận.'"
        ),
        scientific_limitations=tuple(limitations),
        module_owner=module_owner,
        artifact_output_path=(
            f"figures/{{run_id}}/{{split}}/{{business_id}}/{chart_id}.png"
        ),
        notebook_section=notebook_section,
        tests=tuple(tests),
        acceptance_criteria=acceptance_criteria,
        status=status,
        reason=reason,
    )


