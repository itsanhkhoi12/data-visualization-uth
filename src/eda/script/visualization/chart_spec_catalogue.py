CHART_SPECS_V2_BY_ID = {spec.chart_id: spec for spec in CHART_CATALOGUE_V2}


def validate_v2_specs(
    specs: Sequence[ChartSpec] = CHART_CATALOGUE_V2,
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    missing: list[str] = []
    duplicates: list[str] = []
    seen: set[str] = set()
    for spec in specs:
        if spec.chart_id in seen:
            duplicates.append(spec.chart_id)
        seen.add(spec.chart_id)
        required = {
            "title": spec.title,
            "research_question": spec.research_question,
            "reason_for_inclusion": spec.reason_for_inclusion,
            "analysis_level": spec.analysis_level,
            "applicable_data_type": spec.applicable_data_type,
            "statistical_method": spec.statistical_method,
            "calculation_or_formula": spec.calculation_or_formula,
            "chart_type": spec.chart_type,
            "x_axis": spec.x_axis,
            "y_axis": spec.y_axis,
            "unit": spec.unit,
            "grouping": spec.grouping,
            "sampling_strategy": spec.sampling_strategy,
            "missing_handling": spec.missing_handling,
            "outlier_handling": spec.outlier_handling,
            "scientific_limitations": spec.scientific_limitations,
            "module_owner": spec.module_owner,
            "artifact_output_path": spec.artifact_output_path,
            "notebook_section": spec.notebook_section,
            "tests": spec.tests,
            "acceptance_criteria": spec.acceptance_criteria,
        }
        for field_name, value in required.items():
            if not value:
                missing.append(f"{spec.chart_id}.{field_name}")
    return tuple(missing), tuple(duplicates)


def family_of(chart_id: str) -> str:
    for family in ALL_FAMILIES:
        if chart_id.startswith(family):
            return family
    return "UNKNOWN"


def catalogue_payload() -> dict[str, Any]:
    counts: dict[str, int] = {}
    for spec in CHART_CATALOGUE_V2:
        family = family_of(spec.chart_id)
        counts[family] = counts.get(family, 0) + 1
    return {
        "spec_version": SPEC_VERSION,
        "chart_count": len(CHART_CATALOGUE_V2),
        "family_counts": dict(sorted(counts.items())),
        "charts": [spec.to_dict() for spec in CHART_CATALOGUE_V2],
    }
